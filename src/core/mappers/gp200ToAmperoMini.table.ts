// curated gp-200 -> ampero mini model table
// key: "<gp-200 module>/<gp-200 effect name>" as listed in the vendored effect tables
//
// match levels:
//   exact      same real-world gear, same controls
//   close      same gear (or same effect type) with different controls or voicing
//   substitute no equivalent; nearest model of the same kind
//   none       no usable equivalent on the ampero mini

export type MatchLevel = 'exact' | 'close' | 'substitute' | 'none';

export interface MapEntry {
  // ampero model name; null when match is 'none'
  to: string | null;
  match: MatchLevel;
  // source param name -> target param name (null = drop); unlisted params use auto matching
  params?: Record<string, string | null>;
  // fixed target values to set (e.g. a waveform choice)
  set?: Record<string, string | number>;
  note?: string;
}

// compact builders
const ex = (to: string, extra: Partial<MapEntry> = {}): MapEntry => ({ to, match: 'exact', ...extra });
const cl = (to: string, extra: Partial<MapEntry> = {}): MapEntry => ({ to, match: 'close', ...extra });
const sub = (to: string, extra: Partial<MapEntry> = {}): MapEntry => ({ to, match: 'substitute', ...extra });
const none = (note: string): MapEntry => ({ to: null, match: 'none', note });

